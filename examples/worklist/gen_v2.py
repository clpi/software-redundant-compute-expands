# Builds an append trace of canonical records from the idol-lib
# version 2 source graphs. Read-only on the checkout; runs nothing.
# Encoding (stated, not inferred from the graphs):
#  * each hyperedge is one record at level 0, colors [2] (observed
#    source record), premises = its premise nodes in order,
#    head = its conclusion node ("requires: all" is exactly
#    viewC's conjunction);
#  * the graphs set roots to null. The only nodes no edge concludes
#    are `file` nodes (inspected source bytes, checked by the
#    generator's SHA-256 manifest). Each becomes a zero-premise
#    record, colors [2]. Without these the view derives nothing.
#  * append order: libraries in sorted order; within a library its
#    file records in node order, then its edges in edge order.
# Usage: python3 gen_v2.py IDOL_LIB_CHECKOUT OUT.lean
import json, os, sys
il, out = sys.argv[1:3]
libs = sorted(d for d in os.listdir(os.path.join(il, "graphs"))
              if os.path.isfile(os.path.join(il, "graphs", d, "graph.json")))
terms, recs = {}, []
def t(x):
    if x not in terms: terms[x] = len(terms)
    return terms[x]
for lib in libs:
    g = json.load(open(os.path.join(il, "graphs", lib, "graph.json")))
    heads = {e["conclusion"] for e in g["edges"]}
    for n in g["nodes"]:
        if n["id"] not in heads:
            assert n["kind"] == "file", (lib, n["kind"])
            recs.append(([], t(n["id"]), lib))
    for e in g["edges"]:
        recs.append(([t(p) for p in e["premises"]], t(e["conclusion"]), lib))
L = ["import Canon", "/-! Generated by examples/worklist/gen_v2.py. Do not edit. -/",
     "namespace V2", "open Canon", "",
     "def libs : Array String := #[" + ", ".join(json.dumps(r[2]) for r in recs) + "]", "",
     "def log : List Rec := ["]
L += ["  ⟨%d, 0, [2], %s, %d⟩," % (i, json.dumps(p), h) for i, (p, h, _) in enumerate(recs)]
L[-1] = L[-1].rstrip(",")
L += ["]", "", "end V2", ""]
open(out, "w").write("\n".join(L))
print(json.dumps({"libraries": len(libs), "records": len(recs), "terms": len(terms),
                  "roots": sum(1 for p, _, _ in recs if not p)}))
